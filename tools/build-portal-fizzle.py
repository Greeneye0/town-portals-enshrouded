"""Synthesize the fizzle Town Portal plays when a cast is interrupted, and embed it as a WAV.

About 0.55 s: a sputter of crackling noise over a tone falling from 520 to 90 Hz, fading out,
like magic dying. Deterministic (fixed seed), so the header is reproducible.

Run: python -I tools/build-portal-fizzle.py  ->  src/portal_fizzle.h
"""
import math, random, struct
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RATE = 32000
LENGTH = 0.55
PEAK = 0.245        # the same peak as the portal sounds (portal_sounds.h)

random.seed(20261027)
n = int(RATE * LENGTH)
samples = []
phase = 0.0
low = 0.0           # one-pole low-pass state for the hiss
for i in range(n):
    t = i / RATE
    x = t / LENGTH
    envelope = min(1.0, t / 0.012) * (1 - x) ** 2.2
    # Falling tone with a little wobble.
    freq = 90 + 430 * (1 - x) ** 1.6
    phase += 2 * math.pi * freq * (1 + 0.04 * math.sin(2 * math.pi * 23 * t)) / RATE
    tone = 0.45 * math.sin(phase) + 0.15 * math.sin(2.01 * phase)
    # Hiss, low-passed, and crackle: random sharp pops, denser at the start.
    low += 0.35 * (random.uniform(-1, 1) - low)
    hiss = 0.35 * low
    crackle = 0.0
    if random.random() < 0.012 * (1 - x) + 0.002:
        crackle = random.choice((-1, 1)) * random.uniform(0.5, 1.0)
    samples.append((tone + hiss) * envelope + crackle * envelope * 0.9)

# Smooth the pops a touch so they click less.
smoothed = [samples[0]] + [0.6 * samples[i] + 0.4 * samples[i - 1] for i in range(1, n)]
peak = max(abs(s) for s in smoothed) or 1.0
pcm = b''.join(struct.pack('<h', int(max(-1, min(1, s * PEAK / peak)) * 32767)) for s in smoothed)
data = struct.pack('<4sI4s4sIHHIIHH4sI', b'RIFF', 36 + len(pcm), b'WAVE', b'fmt ', 16, 1, 1,
                   RATE, RATE * 2, 2, 16, b'data', len(pcm)) + pcm

out = ['// Generated by tools/build-portal-fizzle.py (synthesized). Do not edit.',
       '#pragma once', '#include <cstdint>', 'namespace portal::sounds {',
       f'alignas(4) inline constexpr uint8_t kFizzleWav[{len(data)}] = {{']
out.extend(','.join(str(b) for b in data[i:i + 32]) + ',' for i in range(0, len(data), 32))
out += ['};', '}']
(ROOT / 'src/portal_fizzle.h').write_text('\n'.join(out) + '\n', encoding='utf-8')
print(f'kFizzleWav: {len(data)} bytes, {LENGTH} s')
(ROOT / 'tools/fizzle-preview.wav').write_bytes(data)
