"""Cut Town Portal's two sounds from the portal whoosh and embed them as WAV byte arrays.

Source: assets/sounds/virtualzero-whoosh-sci-fi-portal-hd-374800.mp3 (8 s, chosen by the
user). It holds two events: a short whoosh (0.3-1.7 s) and a long sustained portal sound
(2.3-8 s).
- summon: 3 s of the sustained portal sound, for the 3 s channel (kPortalFormMs);
- travel: the whoosh, played when the player steps through.

Needs ffmpeg on PATH. Run: python -I tools/build-portal-sounds.py  ->  src/portal_sounds.h
"""
import struct, subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'assets/sounds/virtualzero-whoosh-sci-fi-portal-hd-374800.mp3'
RATE = 32000
PEAK = 0.245 # Windows audio ignores the game's volume slider; the source peaks at 0.31 (0.7, then 0.35, were too loud)

def decode():
    raw = subprocess.run(['ffmpeg', '-hide_banner', '-loglevel', 'error', '-i', str(SOURCE),
                          '-ac', '1', '-ar', str(RATE), '-f', 'f32le', '-'],
                         check=True, capture_output=True).stdout
    return list(struct.unpack(f'<{len(raw)//4}f', raw))

def cut(samples, start, end, fadeIn, fadeOut):
    part = samples[int(start*RATE):int(end*RATE)]
    n = len(part)
    for i in range(n):
        t = i / RATE
        gain = min(1.0, t/fadeIn if fadeIn else 1.0, (n/RATE - t)/fadeOut if fadeOut else 1.0)
        part[i] *= max(0.0, gain)
    return part

def wav(samples, scale):
    pcm = b''.join(struct.pack('<h', int(max(-1, min(1, x*scale)) * 32767)) for x in samples)
    header = struct.pack('<4sI4s4sIHHIIHH4sI', b'RIFF', 36 + len(pcm), b'WAVE', b'fmt ', 16, 1, 1,
                         RATE, RATE * 2, 2, 16, b'data', len(pcm))
    return header + pcm

full = decode()
summon = cut(full, 2.25, 5.30, 0.05, 0.45)
travel = cut(full, 0.25, 1.85, 0.02, 0.25)
# One scale for both keeps the two parts as loud relative to each other as in the source.
scale = PEAK / max(abs(x) for x in summon + travel)
sounds = {'kSummonWav': wav(summon, scale), 'kTravelWav': wav(travel, scale)}

lines = ['// Generated by tools/build-portal-sounds.py from assets/sounds/virtualzero-whoosh-sci-fi-portal-hd-374800.mp3.',
         '#pragma once', '#include <cstdint>', 'namespace portal::sounds {']
for name, data in sounds.items():
    lines.append(f'alignas(4) inline constexpr uint8_t {name}[{len(data)}] = {{')
    for i in range(0, len(data), 32):
        lines.append(','.join(str(b) for b in data[i:i + 32]) + ',')
    lines.append('};')
lines.append('}')
(ROOT / 'src/portal_sounds.h').write_text('\n'.join(lines) + '\n')
out = ROOT / 'assets/sounds'
(out / 'portal-summon.wav').write_bytes(sounds['kSummonWav'])
(out / 'portal-travel.wav').write_bytes(sounds['kTravelWav'])
print({name: f'{(len(data) - 44) / 2 / RATE:.2f} s' for name, data in sounds.items()}, f'scale {scale:.2f}')
