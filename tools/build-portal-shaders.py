"""Compile the portal's native Vulkan shaders into reproducible C++ arrays."""
import pathlib, subprocess, struct
root=pathlib.Path(__file__).resolve().parents[1]
compiler=pathlib.Path(r'C:\temp\enshrouded-re\glslang-build\StandAlone\Release\glslang.exe')
out=['// Generated by tools/build-portal-shaders.py. Edit src/shaders instead.']
# (source file, array name): the portal surface and the snapshot capture (portal_snapshot.frag).
for name,array in (('portal_composite.vert','kComposite_vert'),('portal_composite.frag','kComposite_frag'),
                   ('portal_snapshot.frag','kSnapshot_frag')):
    src=root/'src/shaders'/name
    dst=root/'tools'/(name+'.spv')
    subprocess.run([str(compiler),'-V','--target-env','vulkan1.2','-o',str(dst),str(src)],check=True)
    b=dst.read_bytes(); words=struct.unpack('<'+'I'*(len(b)//4),b)
    out.append('inline constexpr uint32_t '+array+'[] = {')
    out.extend('  '+','.join('0x%08xu'%w for w in words[i:i+8])+',' for i in range(0,len(words),8))
    out.append('};')
(root/'src/portal_composite_shaders.h').write_text('\n'.join(out)+'\n')
