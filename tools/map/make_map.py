"""The loading-screen map: texture and world-to-map warp.

assets/map/map-source-blank.png (the painted map, its labels painted out by erase_labels.py;
labels are written in game) -> assets/map/map.jpg (1024x1024), and for English the painting as
supplied, map-source-en.png -> map-en.jpg
and src/portal_map_warp.h: a thin-plate spline from world metres (x east, z north) to the map's
0..1 texture coordinates, exact at the landmarks below. The art is not to scale, so a plain
affine fit is off by up to 700 m; the spline bends it to the painted spires instead.
Pillars of Creation is painted ~1.6 km north of where it stands and is left out (honouring it
would drag the whole middle of the map). The region centres anchor areas with no landmark.
Run: python make_map.py
"""
import os
import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..', '..')
SOURCE = os.path.join(ROOT, 'assets', 'map', 'map-source-blank.png')  # erase_labels.py: banners without text
TEXTURE = os.path.join(ROOT, 'assets', 'map', 'map.jpg')
# English shows the painting as supplied, its own lettering; other languages the blank one with labels drawn.
SOURCE_EN = os.path.join(ROOT, 'assets', 'map', 'map-source-en.png')
TEXTURE_EN = os.path.join(ROOT, 'assets', 'map', 'map-en.jpg')
HEADER = os.path.join(ROOT, 'src', 'portal_map_warp.h')
SIZE = 1024

# name: world x, z (src/portal_locations.h; centres from the region map) -> source pixel u, v
# (read off the 1254 px painting: spire tower bases, landmark centres).
ART = 1254
POINTS = {
    'Veilwater Spire': (4737.97, 5531.16, 578, 435),
    'Blackmire Spire': (3413.21, 5561.15, 480, 585),
    'Revelwood Spire': (3830.15, 3646.47, 480, 780),
    'Springlands Spire': (3507.97, 1957.16, 480, 1000),
    'Low Meadows Spire': (4910.52, 1652.16, 615, 1065),
    'Albaneve Spire': (7451.19, 4932.59, 928, 575),
    'Nomad Spire': (6766.19, 3764.0, 865, 825),
    'Kindlewastes Spire': (8402.62, 2468.57, 1028, 935),
    'Umber Hollow': (6384.83, 2937.67, 780, 880),
    "Cinder's Cradle centre": (6962, 8770, 780, 165),
    'Veilwater Basin centre': (4244, 6279, 440, 330),
    'Kindlewastes centre': (8377, 1791, 990, 1040),
}


def fit():
    km = np.array([[x / 1000, z / 1000] for x, z, _, _ in POINTS.values()])
    uv = np.array([[u / ART, v / ART] for *_, u, v in POINTS.values()])
    n = len(km)
    r = np.linalg.norm(km[:, None] - km[None], axis=2)
    K = np.where(r > 0, r * r * np.log(np.where(r > 0, r, 1)), 0)
    Q = np.hstack([np.ones((n, 1)), km])
    L = np.zeros((n + 3, n + 3))
    L[:n, :n], L[:n, n:], L[n:, :n] = K, Q, Q.T
    W = np.linalg.solve(L, np.vstack([uv, np.zeros((3, 2))]))
    return km, W


def header(km, W):
    n = len(km)
    rows = ',\n    '.join(f'{{{x:.4f},{z:.4f},{W[i,0]:.9g},{W[i,1]:.9g}}}' for i, (x, z) in enumerate(km))
    names = '\n'.join(f'//   {name}' for name in POINTS)
    return f'''#pragma once
// Generated by tools/map/make_map.py; do not edit. World metres (x east, z north) to the
// loading-screen map's texture coordinates (0..1, v down): a thin-plate spline through the
// painted landmarks:
{names}
#include <cmath>

namespace portal::mapwarp {{
struct Centre {{ double x, z, wu, wv; }}; // km, and the spline weights for u and v
constexpr Centre kCentres[{n}] = {{
    {rows}}};
constexpr double kAffine[3][2] = {{{{{W[n,0]:.9g},{W[n,1]:.9g}}},{{{W[n+1,0]:.9g},{W[n+1,1]:.9g}}},{{{W[n+2,0]:.9g},{W[n+2,1]:.9g}}}}};

inline void ToMap(double x, double z, double& u, double& v) {{
    x /= 1000; z /= 1000;
    u = kAffine[0][0] + kAffine[1][0] * x + kAffine[2][0] * z;
    v = kAffine[0][1] + kAffine[1][1] * x + kAffine[2][1] * z;
    for (const auto& c : kCentres) {{
        const double r = std::sqrt((x - c.x) * (x - c.x) + (z - c.z) * (z - c.z));
        if (r <= 0) continue;
        const double k = r * r * std::log(r);
        u += c.wu * k; v += c.wv * k;
    }}
}}
}}
'''


def main():
    km, W = fit()
    with open(HEADER, 'w', encoding='utf-8', newline='\n') as f:
        f.write(header(km, W))
    for source, texture in ((SOURCE, TEXTURE), (SOURCE_EN, TEXTURE_EN)):
        im = Image.open(source).convert('RGB').resize((SIZE, SIZE), Image.LANCZOS)
        im.save(texture, quality=90, optimize=True, subsampling=0)
    print(f'{os.path.basename(TEXTURE)} {os.path.getsize(TEXTURE) // 1024} KB, {os.path.basename(HEADER)} with {len(km)} landmarks')


if __name__ == '__main__':
    main()
